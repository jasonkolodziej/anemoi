/**
 * Plain-text fallback for the magic link email.
 */
function getMagicLinkText(url: string): string {
	return [
		"Sign in to Anemoi",
		"",
		"Click the link below to sign in. This link expires in 5 minutes.",
		"",
		url,
		"",
		"If you didn't request this email, you can safely ignore it.",
		"",
		"— Anemoi",
	].join("\n");
}

