/**
 * Magic link email delivery via Cloudflare Email Routing.
 *
 * Uses the `send_email` Worker binding (configured in wrangler.jsonc)
 * to send sign-in/sign-up emails. The binding's builder overload
 * accepts `{ from, to, subject, html, text }` directly — no need for
 * a third-party MIME library.
 *
 *
 * **Summary of local dev behavior:**
 *
 * | Mode | `binding` value | Emails sent? |
 * |------|-----------------|--------------|
 * | `wrangler dev` (no `remote`) | non-null (simulated) | No — logged to console + temp files |
 * | `wrangler dev` + `remote: true` | non-null (real binding) | Yes — real emails delivered |
 * | No binding configured at all | `null` | Falls back to `console.warn` |
 *
 * One caveat from the docs: `remote: true` sends real emails to real recipients, so use test addresses during dev.
 * Binary attachment `ArrayBuffer` values also can't be serialized in the local simulator — not a concern here since the magic link and OTP templates use only strings.
 *
 * **Requirements:**
 * - Email Routing must be enabled on the sender domain (anemoi.systems).
 * - The `SEND_EMAIL` binding must be configured in `wrangler.jsonc`.
 *
 * @see https://developers.cloudflare.com/email-routing/email-workers/send-email-workers/
 */

// ─── Constants ───────────────────────────────────────────────────────────────

const SENDER_NAME = "Anemoi";
const SENDER_EMAIL = "service-noreply+auth@anemoi.systems";

// ─── OTP Email ───────────────────────────────────────────────────────────────

type OtpType =
	| "sign-in"
	| "email-verification"
	| "forget-password"
	| "change-email";

const OTP_SUBJECTS: Record<OtpType, string> = {
	"sign-in": "Your Anemoi sign-in code",
	"email-verification": "Verify your Anemoi email",
	"forget-password": "Your Anemoi password reset code",
	"change-email": "Confirm your new Anemoi email",
};

/**
 * Send an OTP email using the Cloudflare Email Routing binding.
 * Falls back to console in local dev when the binding is unavailable.
 * The binding is passed in by auth.ts's per-request `buildAuth` rather
 * than kept in a module variable -- Workers do run concurrent requests on
 * one isolate, so module state is not request-scoped.
 */
export async function sendVerificationOTPEmail(
	binding: SendEmail | null,
	email: string,
	otp: string,
	type: OtpType,
): Promise<void> {
	if (!binding) {
		console.warn(
			`[OTP] SEND_EMAIL binding not available. Falling back to console.\n` +
				`  To: ${email}\n` +
				`  Type: ${type}\n` +
				`  OTP: ${otp}`,
		);
		return;
	}

	try {
		await binding.send({
			from: { name: SENDER_NAME, email: SENDER_EMAIL },
			to: email,
			subject: OTP_SUBJECTS[type],
			text: getOtpText(otp, type),
			html: getOtpHtml(otp, type),
		});
	} catch (err) {
		console.error(
			`[OTP] Failed to send email to ${email}:`,
			err instanceof Error ? err.message : err,
		);
		throw new Error("Failed to send OTP email. Please try again.");
	}
}

// ─── Magic Link Email ────────────────────────────────────────────────────────

/**
 * Send a magic link email using the Cloudflare Email Routing binding.
 *
 * If the binding is unavailable (e.g. local dev without email routing),
 * falls back to `console.log` so that magic links still work during
 * development.
 *
 * @param binding - This request's `SEND_EMAIL` binding (`null` when unbound)
 * @param email   - Recipient email address
 * @param url     - The magic link verification URL (generated by better-auth)
 */
export async function sendMagicLinkEmail(
	binding: SendEmail | null,
	email: string,
	url: string,
): Promise<void> {
	if (!binding) {
		console.warn(
			`[Magic Link] SEND_EMAIL binding not available. Falling back to console.\n` +
				`  To: ${email}\n` +
				`  URL: ${url}`,
		);
		return;
	}

	try {
		await binding.send({
			from: { name: SENDER_NAME, email: SENDER_EMAIL },
			to: email,
			subject: "Sign in to Anemoi",
			text: getMagicLinkText(url),
			html: getMagicLinkHtml(url),
		});
	} catch (err) {
		console.error(
			`[Magic Link] Failed to send email to ${email}:`,
			err instanceof Error ? err.message : err,
		);
		// Re-throw so better-auth can surface the error to the client
		throw new Error("Failed to send magic link email. Please try again.");
	}
}

